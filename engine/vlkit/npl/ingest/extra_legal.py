def register(retrieved_at=None, status=None):
    """The curated rows as a DataFrame, with per-row URL reachability when the caller verified it."""
    frame = pd.DataFrame(REGISTER)
    lookup = [LOOKUP.format(ref=ref.replace("/", "%2F")) for ref in frame["ref"]]
    if "url" not in frame:
        frame["url"] = lookup
    else:
        frame["url"] = frame["url"].fillna(pd.Series(lookup, index=frame.index))
    frame["retrieved_at"] = retrieved_at
    frame["http_status"] = status
    return frame[COLUMNS + ["http_status"]]


def run(lake, fetcher, run_id, retrieved_at):
    """Verify each lookup URL (bronze lands the response), then write silver/legal_register.csv."""
    rows, status = [], {}
    for row in REGISTER:
        url = LOOKUP.format(ref=row["ref"].replace("/", "%2F"))
        try:
            response = fetcher.get(url)
        except FetchError as exc:
            status[row["ref"]] = str(exc)[-40:][:60]
            continue
        status[row["ref"]] = response.status_code
        land(lake, run_id, "legal", row["ref"], response.content, "html", {"url": url})
        rows.append(row["ref"])
    frame = register(retrieved_at=retrieved_at, status=[status.get(row["ref"]) for row in REGISTER])
    write_silver(lake, "legal_register.csv", frame, {"verified_rows": rows, "lookup": LOOKUP})
    stats = {"rows": len(frame), "verified": len(rows)}
    failed = {ref: value for ref, value in status.items() if not isinstance(value, int) or value != 200}
    if failed:
        stats["errors"] = failed
    return frame, stats
