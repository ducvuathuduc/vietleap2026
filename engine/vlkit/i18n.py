_warned: set[str] = set()


def _check_lang(lang: str) -> str:
    if lang not in LANGS:
        raise ValueError(f"lang must be one of {LANGS}, got {lang!r}")
    return lang


def t(lang: str, key: str, **values) -> str:
    """The fixed string `key` in `lang`, with `values` (already formatted for that language) filled in."""
    return STRINGS[_check_lang(lang)][key].format(**values) if values else STRINGS[_check_lang(lang)][key]


def langs_for(report_lang: str) -> tuple[str, ...]:
    """CLI/API `--lang vi|en|both` → the deck languages to build ('both' → EN then VI)."""
    if report_lang not in REPORT_LANGS:
        raise ValueError(f"lang must be one of {REPORT_LANGS}, got {report_lang!r}")
    return LANGS if report_lang == "both" else (report_lang,)


def text_field(obj: dict, base: str, lang: str) -> str:
    """Engine text `<base>_<lang>` (e.g. title_vi); falls back to English for older results.json, logging once —
    never machine-translated."""
    value = obj.get(f"{base}_{_check_lang(lang)}")
    if value:
        return value
    if lang != "en" and base not in _warned:
        _warned.add(base)
        print(f"[warn] missing {lang.upper()} text: {base} — using English")
    return obj.get(f"{base}_en") or ""


def caveats_for(res: dict, lang: str) -> list[str]:
    """results.json caveats in `lang` (`caveats_vi` is parallel to `caveats`); English for older results.json."""
    if _check_lang(lang) == "vi" and len(res.get("caveats_vi") or []) == len(res["caveats"]):
        return res["caveats_vi"]
    if lang == "vi" and "caveats" not in _warned:
        _warned.add("caveats")
        print("[warn] missing VI text: caveats — using English")
    return res["caveats"]
